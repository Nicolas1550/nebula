import assert from 'node:assert/strict';
import {startMission, collectCore, tickMission, damageShip} from '../lib/infernoRules.ts';
let mission = startMission();
for (let i=0; i<4; i++) mission=collectCore(mission);
assert.equal(mission.energy, 80);
assert.equal(mission.status, 'playing');
mission = collectCore(mission);
assert.equal(mission.energy, 100);
assert.equal(mission.status, 'won', 'el quinto núcleo debe ganar en el mismo evento');
const remaining = mission.time;
mission=tickMission(mission, 100);
assert.equal(mission.time, remaining, 'el reloj debe detenerse al ganar');
assert.equal(mission.status, 'won');
assert.equal(damageShip(mission).hull, 100, 'no puede perder después de ganar');
let lost = tickMission(startMission(), 60);
assert.equal(lost.status, 'lost');
assert.equal(collectCore(lost).energy, 0, 'no puede recoger después de perder');
let broken=startMission();
for (let i=0;i<4;i++) broken=damageShip(broken);
assert.equal(broken.status, 'lost');
assert.equal(broken.hull,0);
console.log('PASS: INFERNO victoria, reloj congelado, derrota y estados terminales');
